// Generates artifacts/SystemTest/test_scenarios.md and requirement_traceability.md
// from simulator/web/scenarios.js so the documents and the simulator never diverge.
const fs = require("fs");
const path = require("path");
const { scenarios } = require("./web/scenarios.js");
const Sim = require("./web/sim-core.js");
const out = path.join(__dirname, "..", "artifacts", "SystemTest");

const cells = (sc, kind) => {
  const { obstacle, dust } = Sim.parseMap(sc.map);
  const list = [];
  for (let y = 0; y < 10; y++) for (let x = 0; x < 10; x++) {
    if (kind === "#" && obstacle[y][x]) list.push(`(${x},${y})`);
    if (kind === "d" && dust[y][x]) list.push(`(${x},${y})x${dust[y][x]}`);
  }
  return list.length ? list.join(", ") : "None";
};

let md = `# RVC System Test Scenarios

Generated from \`simulator/web/scenarios.js\` by \`node simulator/gen_docs.js\`.
Run them in the web simulator (\`simulator/dist/rvc-simulator.html\`).

## 1. Test Design Policy
- ${scenarios.length} scenarios, 10x10 grid, at most 100 ticks each.
- Each scenario names at least 3 essential system functions, its requirement IDs (PR-x from
  \`artifacts/SA/process_specification.md\`) and the SA artifacts it exercises.
- The test oracle is the human evaluator. The simulator shows requirement-check flags as
  hints only and never assigns PASS or FAIL.
- Coordinates: x = 0..9 (left to right), y = 0..9 (top to bottom). Heading N means toward y = 0.
- Default start (4,4) heading N. The requirements give no initial heading, so N was chosen.

## 2. Environment model (simulator only, not controller behavior)
- Front sensor = the cell ahead is an obstacle or outside the grid; delivered by interrupt
  (only when its value changes). Left/right sensors = the cell to the left/right of the heading;
  dust sensor = dust amount on the current cell > 0; delivered every *side period* ticks (default 1).
- forward / backward move one cell when that cell is free; stop does not move.
- A turn rotates the heading 90 degrees on the turn's 3rd tick (turn angle is not specified by the requirements).
- Each tick with Cleaner = clean_up removes 1 unit of dust from the current cell (dust amounts 1-9 let a
  cell need several clean_up ticks; the requirements do not specify dust amounts).

## 3. Scenarios
`;
for (const sc of scenarios) {
  md += `
### ${sc.id} ${sc.name}

**Initial Configuration**
- Grid: 10x10
- RVC Start: (${sc.start.x},${sc.start.y})
- Initial Direction: ${sc.start.heading}
- Obstacles: ${cells(sc, "#")}
- Dust: ${cells(sc, "d")}
- Left/right/dust sampling period: ${sc.sidePeriod || 1} tick(s); front by interrupt
- Maximum Ticks: 100

**Map**
\`\`\`
${sc.map.join("\n")}
\`\`\`

**Test Objectives**
${sc.functions.map((f, i) => `- Essential Function ${i + 1}: ${f}`).join("\n")}

**Requirement Traceability**
- Related Requirement IDs: ${sc.requirements.join(", ")}
- Related SA Artifacts: ${sc.artifacts.join(", ")}

**Expected Behavior**
${sc.expected}

**Human Evaluation**
- Result: Pending
- Evaluator:
- Observations:
- Related Tick(s):
`;
}
fs.writeFileSync(path.join(out, "test_scenarios.md"), md);

const reqs = ["PR-2", "PR-3", "PR-4", "PR-5", "PR-8", "PR-9", "PR-10", "PR-11", "PR-12", "PR-13", "PR-14", "PR-15", "PR-16", "PR-17"];
let tr = `# Requirement Traceability (System Test)

Generated by \`node simulator/gen_docs.js\`.

## Scenario to requirement

| Scenario ID | Essential Functions | Requirement IDs | SA Artifacts | Human Result |
|---|---|---|---|---|
`;
for (const sc of scenarios) tr += `| ${sc.id} | ${sc.functions.join("; ")} | ${sc.requirements.join(", ")} | ${sc.artifacts.join("; ")} | Pending |\n`;
tr += `\n## Requirement to scenario\n\n| Requirement | Scenarios |\n|---|---|\n`;
for (const r of reqs) tr += `| ${r} | ${scenarios.filter((s) => s.requirements.includes(r)).map((s) => s.id).join(", ") || "-"} |\n`;
tr += `\nPR-1, PR-6 and PR-7 describe scope (automatic cleaning only, no hardware detail) and have no observable behavior of their own.\n`;
fs.writeFileSync(path.join(out, "requirement_traceability.md"), tr);
console.log("wrote test_scenarios.md and requirement_traceability.md");
